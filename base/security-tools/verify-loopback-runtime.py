#!/usr/bin/env python3
"""Run schema-3 against mined LOCAL evidence and intentional tampering.
The pins are generated by the local harness, never trusted production pins.
"""
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
import tempfile

spec=importlib.util.spec_from_file_location("review",Path(__file__).with_name("verify-integrated-runtime.py"))
review=importlib.util.module_from_spec(spec)
spec.loader.exec_module(review)
digest=lambda x:hashlib.sha256(x).hexdigest()
encode=lambda x:json.dumps(x,sort_keys=True,separators=(",",":")).encode()
root=Path(sys.argv[1])
pins=json.loads(Path(str(root)+".pins.json").read_bytes())
assert pins["status"]=="SELF_GENERATED_LOCAL_TEST_PINS_NOT_TRUSTED_RELEASE_PINS"
result=review.verify(root,pins["manifest"],pins["state"],pins["plans"],pins["code"],pins["review_timestamp"])
assert result["status"]=="INTEGRATED_RUNTIME_REVIEW_MATCHES_NO_GO"
assert set(result["runtime_contracts"])=={"guard","successor","safe","singleton"}
assert result["testnet"]==result["mainnet"]=="NO_GO"
assert sum(c["immutable_groups"] for c in result["runtime_contracts"].values())==12

# Rebuild the manifest and local observation pin to ensure the semantic
# verifier, rather than only the outer digest, rejects each changed snapshot.
manifest=json.loads((root/"manifest.json").read_bytes())
obs=json.loads((root/"runtime_observations.bin").read_bytes())
def reject(label,changed):
    with tempfile.TemporaryDirectory() as tmp:
        target=Path(tmp)
        for path in root.iterdir():
            (target/path.name).write_bytes(path.read_bytes())
        mutated=encode(changed)
        (target/"runtime_observations.bin").write_bytes(mutated)
        m=copy.deepcopy(manifest)
        m["artifacts"]["runtime_observations"]["sha256"]=digest(mutated)
        manifest_raw=encode(m)
        (target/"manifest.json").write_bytes(manifest_raw)
        try:
            review.verify(target,digest(manifest_raw),pins["state"],pins["plans"],digest(mutated),pins["review_timestamp"])
        except ValueError as exc:
            print("EXPECTED_REJECTION",label,str(exc))
            return
        raise AssertionError("accepted invalid local snapshot "+label)
for role in ("guard","successor","safe","singleton"):
    bad=copy.deepcopy(obs)
    code=bad["contracts"][role]["runtime_hex"]
    bad["contracts"][role]["runtime_hex"]=code[:-2]+("00" if code[-2:]!="00" else "01")
    reject("modified_"+role,bad)
bad=copy.deepcopy(obs);bad["safe_slot0"]="00"*32;reject("wrong_mastercopy",bad)
bad=copy.deepcopy(obs);bad["block_number"]+=1;reject("wrong_block",bad)
result["rehearsal_status"]="LOCAL_LOOPBACK_ONLY_NO_INDEPENDENT_PINS"
result["expected_rejections"]=6
result["rehearsal_limitations"]="Actual local mined bytes, state and unsigned payload; opaque non-runtime evidence roles are explicitly labeled references/placeholders. The same local harness generated plans, observations and test pins. No public chain, independent release review or authorization."
Path(sys.argv[2]).write_text(json.dumps(result,indent=2)+"\n")
print("LOCAL_FROZEN_RUNTIME_VERIFIED_NO_GO",len(result["runtime_contracts"]),"contracts; six semantic rejections")
